"""Compile jisp's JAX DSL to a Python module of pure-JAX functions.

DSL (top-level forms):

    (let-dim <name> <dim> ...)       bind name/dim pairs at compile time;
                                     later pairs may reference earlier ones
    (define <name> <block>)

A block position also accepts the name of an earlier define, compiling to
calls of that block's functions. Each reference initializes fresh params —
a define is a template, not weight sharing.

Blocks:
    (mlp <in> [<hidden>...] <out> <activation>?)
                                     dense layers; <activation> is an optional
                                     symbol (relu gelu silu sigmoid tanh),
                                     default gelu, applied after each hidden
                                     layer (never after the output layer)
    (layernorm <dim>)
    (attention <dim> <heads>)        multi-head self-attention over (..., seq, dim)
    (chain <block> <block>...)       sequential composition
    (residual <block>)               x + block(x); block must preserve dim
    (repeat <count> <block>)         count copies with independent params;
                                     block must preserve dim

A <dim> is a compile-time expression evaluated by the jisp interpreter:
an int literal, a let-dim name, arithmetic like (* 4 d), or coefficient
sugar like 4d (meaning (* 4 d)). Brackets [...] are data tuples, used for
mlp hidden dims.

Each define compiles to a pair of functions in the output module:
init_<name>(key) building a params pytree, and <name>(params, x).
"""

import re
import sys
from pathlib import Path

from jisp import EvalError, ParseError, evaluate, parse, standard_env


class CompileError(Exception):
    """Raised when parsed forms are not a valid jisp JAX program."""


HEADER = '''"""Generated by jisp — do not edit."""

import jax
import jax.numpy as jnp
'''

HELPERS = {
    "dense": '''
def init_dense(key, in_dim, out_dim):
    W = jax.random.normal(key, (in_dim, out_dim)) * jnp.sqrt(2.0 / in_dim)
    b = jnp.zeros(out_dim)
    return W, b
''',
    "attention": '''
def split_heads(x, heads):
    *batch, seq, dim = x.shape
    return x.reshape(*batch, seq, heads, dim // heads).swapaxes(-3, -2)


def merge_heads(x):
    x = x.swapaxes(-3, -2)
    *batch, seq, heads, head_dim = x.shape
    return x.reshape(*batch, seq, heads * head_dim)
''',
}


ACTIVATIONS = {
    "relu": "jax.nn.relu",
    "gelu": "jax.nn.gelu",
    "silu": "jax.nn.silu",
    "sigmoid": "jax.nn.sigmoid",
    "tanh": "jnp.tanh",
}


class _DimEnv(dict):
    """Evaluator env for dims: builtins + let-dim bindings + 4d sugar."""

    def __missing__(self, name):
        coeff = re.fullmatch(r"(\d+)([A-Za-z_]\w*)", name)
        if coeff and coeff.group(2) in self:
            return int(coeff.group(1)) * self[coeff.group(2)]
        raise KeyError(name)


def compile_source(source):
    """Compile jisp DSL source to Python module source."""
    defs = []
    helpers = set()
    registry = {}
    dim_env = _DimEnv(standard_env())
    for form in parse(source):
        match form:
            case ["let-dim", *bindings] if bindings:
                if len(bindings) % 2:
                    raise CompileError(
                        f"let-dim expects name/dim pairs, got {form!r}"
                    )
                for name, value in zip(bindings[::2], bindings[1::2]):
                    if not (isinstance(name, str) and name.isidentifier()):
                        raise CompileError(
                            f"let-dim name must be a symbol, got {name!r}"
                        )
                    if name in dim_env:
                        raise CompileError(f"duplicate let-dim: {name}")
                    dim_env[name] = _resolve_dim(value, dim_env)
                continue
            case ["define", str() as name, block] if name.isidentifier():
                pass
            case _:
                raise CompileError(
                    "top-level form must be (define <name> <block>) or "
                    f"(let-dim <name> <dim> ...), got {form!r}"
                )
        if name in registry:
            raise CompileError(f"duplicate define: {name}")
        block_defs, in_dim, out_dim, block_helpers, entry = _compile_block(
            name, block, dim_env, registry
        )
        if entry != name:
            block_defs = block_defs + [f'''
def init_{name}(key):
    return init_{entry}(key)


def {name}(params, x):
    return {entry}(params, x)
''']
        registry[name] = (in_dim, out_dim)
        defs.extend(block_defs)
        helpers |= block_helpers
    if not defs:
        raise CompileError("no forms to compile")
    parts = [HEADER]
    for helper in ("dense", "attention"):
        if helper in helpers:
            parts.append(HELPERS[helper])
    parts.extend(defs)
    return "\n".join(parts)


def _resolve_dim(form, dim_env):
    """Evaluate a dim expression to a positive int."""
    try:
        value = evaluate(form, dim_env)
    except EvalError as exc:
        raise CompileError(f"bad dim {form!r}: {exc}") from None
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    if not isinstance(value, int) or value <= 0:
        raise CompileError(f"dim must be a positive int, got {value!r} from {form!r}")
    return value


def _compile_block(name, block, dim_env, registry):
    """Compile one block; return (defs, in_dim, out_dim, helpers, entry).

    entry is the function name call sites should use: name for structural
    blocks, the referenced define's own name for block references.
    """
    match block:
        case str() as ref if ref in registry:
            in_dim, out_dim = registry[ref]
            return [], in_dim, out_dim, set(), ref
        case str() as ref:
            raise CompileError(f"undefined block '{ref}'")
        case ["mlp", *args]:
            return (*_compile_mlp(name, *_mlp_spec(args, dim_env)), name)
        case ["layernorm", dim]:
            return (*_compile_layernorm(name, _resolve_dim(dim, dim_env)), name)
        case ["attention", dim_form, heads_form]:
            dim = _resolve_dim(dim_form, dim_env)
            heads = _resolve_dim(heads_form, dim_env)
            if dim % heads:
                raise CompileError(
                    f"attention dim {dim} is not divisible by heads {heads}"
                )
            return (*_compile_attention(name, dim, heads), name)
        case ["chain", *blocks] if blocks:
            return _compile_chain(name, blocks, dim_env, registry)
        case ["residual", sub_block]:
            return _compile_residual(name, sub_block, dim_env, registry)
        case ["repeat", count_form, sub_block]:
            count = _resolve_dim(count_form, dim_env)
            return _compile_repeat(name, count, sub_block, dim_env, registry)
        case _:
            raise CompileError(f"unknown block: {block!r}")


def _mlp_spec(args, dim_env):
    activation = "gelu"
    match args:
        case [in_dim, tuple() as hidden, out_dim]:
            pass
        case [in_dim, tuple() as hidden, out_dim, str() as activation]:
            pass
        case [_, list() as hidden, *_]:
            raise CompileError(
                f"mlp hidden dims must be a bracket tuple like [256 256], "
                f"got ({' '.join(map(str, hidden))})"
            )
        case _:
            raise CompileError(
                f"mlp expects (mlp <in> [<hidden>...] <out> <activation>?), "
                f"got {args!r}"
            )
    if activation not in ACTIVATIONS:
        raise CompileError(
            f"unknown activation '{activation}', "
            f"expected one of: {' '.join(sorted(ACTIVATIONS))}"
        )
    dims = [_resolve_dim(d, dim_env) for d in (in_dim, *hidden, out_dim)]
    return dims, activation


def _compile_mlp(name, dims, activation):
    n_layers = len(dims) - 1
    inits = ",\n        ".join(
        f"init_dense(keys[{i}], {dims[i]}, {dims[i + 1]})" for i in range(n_layers)
    )
    defs = f'''
def init_{name}(key):
    keys = jax.random.split(key, {n_layers})
    return [
        {inits},
    ]


def {name}(params, x):
    for W, b in params[:-1]:
        x = {ACTIVATIONS[activation]}(x @ W + b)
    W, b = params[-1]
    return x @ W + b
'''
    return [defs], dims[0], dims[-1], {"dense"}


def _compile_layernorm(name, dim):
    defs = f'''
def init_{name}(key):
    return jnp.ones({dim}), jnp.zeros({dim})


def {name}(params, x):
    scale, shift = params
    mean = x.mean(axis=-1, keepdims=True)
    var = x.var(axis=-1, keepdims=True)
    return scale * (x - mean) / jnp.sqrt(var + 1e-5) + shift
'''
    return [defs], dim, dim, set()


def _compile_attention(name, dim, heads):
    head_dim = dim // heads
    defs = f'''
def init_{name}(key):
    keys = jax.random.split(key, 4)
    return [jax.random.normal(k, ({dim}, {dim})) * jnp.sqrt(1.0 / {dim}) for k in keys]


def {name}(params, x):
    Wq, Wk, Wv, Wo = params
    q = split_heads(x @ Wq, {heads})
    k = split_heads(x @ Wk, {heads})
    v = split_heads(x @ Wv, {heads})
    scores = q @ k.swapaxes(-1, -2) / jnp.sqrt({head_dim})
    out = jax.nn.softmax(scores, axis=-1) @ v
    return merge_heads(out) @ Wo
'''
    return [defs], dim, dim, {"attention"}


def _compile_residual(name, block, dim_env, registry):
    defs, sub_in, sub_out, helpers, entry = _compile_block(
        f"{name}_inner", block, dim_env, registry
    )
    if sub_in != sub_out:
        raise CompileError(
            f"residual requires matching in/out dims in {name}, "
            f"got {sub_in} -> {sub_out}"
        )
    defs = defs + [f'''
def init_{name}(key):
    return init_{entry}(key)


def {name}(params, x):
    return x + {entry}(params, x)
''']
    return defs, sub_in, sub_out, helpers, name


def _compile_repeat(name, count, block, dim_env, registry):
    defs, sub_in, sub_out, helpers, entry = _compile_block(
        f"{name}_body", block, dim_env, registry
    )
    if sub_in != sub_out:
        raise CompileError(
            f"repeat requires matching in/out dims in {name}, "
            f"got {sub_in} -> {sub_out}"
        )
    defs = defs + [f'''
def init_{name}(key):
    return [init_{entry}(k) for k in jax.random.split(key, {count})]


def {name}(params, x):
    for layer_params in params:
        x = {entry}(layer_params, x)
    return x
''']
    return defs, sub_in, sub_out, helpers, name


def _compile_chain(name, blocks, dim_env, registry):
    defs = []
    helpers = set()
    dims = []
    entries = []
    for i, sub_block in enumerate(blocks):
        sub_defs, sub_in, sub_out, sub_helpers, entry = _compile_block(
            f"{name}_layer{i}", sub_block, dim_env, registry
        )
        defs.extend(sub_defs)
        helpers |= sub_helpers
        dims.append((sub_in, sub_out))
        entries.append(entry)
    for i in range(len(dims) - 1):
        if dims[i][1] != dims[i + 1][0]:
            raise CompileError(
                f"chain dimension mismatch in {name}: layer {i} outputs "
                f"{dims[i][1]} but layer {i + 1} expects {dims[i + 1][0]}"
            )
    inits = ", ".join(f"init_{e}(keys[{i}])" for i, e in enumerate(entries))
    applies = "\n".join(
        f"    x = {e}(params[{i}], x)" for i, e in enumerate(entries)
    )
    defs.append(f'''
def init_{name}(key):
    keys = jax.random.split(key, {len(blocks)})
    return [{inits}]


def {name}(params, x):
{applies}
    return x
''')
    return defs, dims[0][0], dims[-1][1], helpers, name


def main():
    if len(sys.argv) not in (2, 3):
        print("usage: python compiler.py model.lisp [out.py]", file=sys.stderr)
        sys.exit(2)
    in_path = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) == 3 else str(Path(in_path).with_suffix(".py"))
    with open(in_path) as f:
        source = f.read()
    try:
        output = compile_source(source)
    except (ParseError, CompileError) as exc:
        print(f"compile error: {exc}", file=sys.stderr)
        sys.exit(1)
    with open(out_path, "w") as f:
        f.write(output)
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
