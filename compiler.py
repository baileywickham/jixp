"""Compile jisp's JAX DSL to a Python module of pure-JAX functions.

DSL (top-level forms):

    (let-dim (<name> <dim>) ...)     bind dims at compile time; later
                                     bindings may reference earlier ones.
                                     Flat pairs also work:
                                     (let-dim <name> <dim> ...)
    (define <name> <block>)

A block position also accepts the name of an earlier define, compiling to
calls of that block's functions. Each reference initializes fresh params —
a define is a template, not weight sharing.

Blocks take required args positionally, then Racket-style keyword options:
valued (#:activation gelu) or bare flags (#:causal).

    (mlp <in> [<hidden>...] <out> #:activation <name>?)
                                     dense layers; activation is one of
                                     relu gelu silu sigmoid tanh (default
                                     gelu), applied after each hidden layer
                                     (never after the output layer); dense
                                     layers are bias-free
    (layernorm <dim>)
    (embedding <vocab> <dim>)        lookup table: int token ids (..., seq)
                                     -> (..., seq, dim); its input is the
                                     pseudo-dim "tokens", so it can only
                                     start a model, never continue one
    (attention <dim> <heads> #:causal?)
                                     multi-head self-attention over
                                     (..., seq, dim); the optional #:causal
                                     flag masks future positions
    (chain <block> <block>...)       sequential composition
    (residual <block>...)            x + body(x); body must preserve dim
    (repeat <count> <block>...)      count copies with independent params;
                                     body must preserve dim

residual and repeat bodies chain implicitly: (residual a b) is
(residual (chain a b)).

A <dim> is a compile-time expression evaluated by the jisp interpreter:
an int literal, a let-dim name, arithmetic like (* 4 d), or coefficient
sugar like 4d (meaning (* 4 d)). Brackets [...] are data tuples, used for
mlp hidden dims.

Each define compiles to a pair of functions in the output module:
init_<name>(key) building a params pytree, and <name>(params, x). Names may
use Racket-style hyphens (attn-block); they become underscores in the
generated Python. ';' starts a line comment.
"""

import re
import sys
from pathlib import Path

from jisp import EvalError, ParseError, evaluate, parse, standard_env


class CompileError(Exception):
    """Raised when parsed forms are not a valid jisp JAX program."""


HEADER = '''"""Generated by jisp — do not edit."""

import jax
import jax.numpy as jnp
'''

HELPERS = {
    "dense": '''
def _init_dense(key, in_dim, out_dim):
    return jax.random.normal(key, (in_dim, out_dim)) * jnp.sqrt(2.0 / in_dim)
''',
    "attention": '''
def _split_heads(x, heads):
    *batch, seq, dim = x.shape
    return x.reshape(*batch, seq, heads, dim // heads).swapaxes(-3, -2)


def _merge_heads(x):
    x = x.swapaxes(-3, -2)
    *batch, seq, heads, head_dim = x.shape
    return x.reshape(*batch, seq, heads * head_dim)
''',
}


ACTIVATIONS = {
    "relu": "jax.nn.relu",
    "gelu": "jax.nn.gelu",
    "silu": "jax.nn.silu",
    "sigmoid": "jax.nn.sigmoid",
    "tanh": "jnp.tanh",
}


class _DimEnv(dict):
    """Evaluator env for dims: builtins + let-dim bindings + 4d sugar."""

    def __missing__(self, name):
        coeff = re.fullmatch(r"(\d+)([A-Za-z_]\w*)", name)
        if coeff and coeff.group(2) in self:
            return int(coeff.group(1)) * self[coeff.group(2)]
        raise KeyError(name)


def _sub_name(parent, suffix):
    """Derive the private (underscore-prefixed) name of an internal sub-block."""
    base = parent if parent.startswith("_") else f"_{parent}"
    return f"{base}_{suffix}"


def _init_of(fn):
    """Name of the init function paired with the apply function fn."""
    return f"_init_{fn[1:]}" if fn.startswith("_") else f"init_{fn}"


def _mangle(name):
    """Map a DSL name to the Python identifier used in generated code."""
    return name.replace("-", "_")


def _valid_name(name):
    return isinstance(name, str) and _mangle(name).isidentifier()


def compile_source(source):
    """Compile jisp DSL source to Python module source."""
    defs = []
    helpers = set()
    registry = {}
    mangled_names = set()
    dim_env = _DimEnv(standard_env())
    for form in parse(source):
        match form:
            case ["let-dim", *bindings] if bindings:
                for name, value in _let_dim_pairs(bindings, form):
                    if not _valid_name(name):
                        raise CompileError(
                            f"let-dim name must be a symbol, got {name!r}"
                        )
                    if name in dim_env:
                        raise CompileError(f"duplicate let-dim: {name}")
                    dim_env[name] = _resolve_dim(value, dim_env)
                continue
            case ["define", str() as name, block] if _valid_name(name):
                pass
            case _:
                raise CompileError(
                    "top-level form must be (define <name> <block>) or "
                    f"(let-dim (<name> <dim>) ...), got {form!r}"
                )
        if name in registry:
            raise CompileError(f"duplicate define: {name}")
        mangled = _mangle(name)
        if mangled in mangled_names:
            raise CompileError(
                f"define '{name}' collides with an earlier define "
                f"(both become '{mangled}' in Python)"
            )
        mangled_names.add(mangled)
        block_defs, in_dim, out_dim, block_helpers, entry = _compile_block(
            mangled, block, dim_env, registry
        )
        if entry != mangled:
            block_defs = block_defs + [f'''
def init_{mangled}(key):
    return {_init_of(entry)}(key)


def {mangled}(params, x):
    return {entry}(params, x)
''']
        registry[name] = (in_dim, out_dim, mangled)
        defs.extend(block_defs)
        helpers |= block_helpers
    if not defs:
        raise CompileError("no forms to compile")
    public = [
        fn for _, _, mangled in registry.values()
        for fn in (f"init_{mangled}", mangled)
    ]
    exports = "\n".join(f'    "{fn}",' for fn in public)
    parts = [HEADER, f"\n__all__ = [\n{exports}\n]\n"]
    for helper in ("dense", "attention"):
        if helper in helpers:
            parts.append(HELPERS[helper])
    parts.extend(defs)
    return "\n".join(parts)


def _is_keyword(value):
    return isinstance(value, str) and value.startswith("#:")


def _parse_options(args, spec, block):
    """Split block args into leading positionals and trailing keyword options.

    spec maps each keyword to "flag" (bare) or "value" (consumes the next
    arg). Returns (positionals, options) with flag options stored as True.
    """
    positionals = []
    options = {}
    i = 0
    while i < len(args) and not _is_keyword(args[i]):
        if isinstance(args[i], str) and args[i].startswith(":"):
            raise CompileError(
                f"{block}: options use Racket keyword syntax, e.g. #{args[i]}"
            )
        positionals.append(args[i])
        i += 1
    while i < len(args):
        keyword = args[i]
        if not _is_keyword(keyword):
            raise CompileError(
                f"{block}: positional arg {keyword!r} after keyword options"
            )
        if keyword not in spec:
            raise CompileError(
                f"unknown {block} option {keyword}, "
                f"expected one of: {' '.join(sorted(spec))}"
            )
        if keyword in options:
            raise CompileError(f"duplicate {block} option {keyword}")
        if spec[keyword] == "flag":
            options[keyword] = True
            i += 1
        else:
            if i + 1 >= len(args) or _is_keyword(args[i + 1]):
                raise CompileError(f"{block} option {keyword} expects a value")
            options[keyword] = args[i + 1]
            i += 2
    return positionals, options


def _let_dim_pairs(bindings, form):
    """Normalize let-dim bindings to (name, value) pairs.

    Grouped form (let-dim (d 128) [heads 8] ...) when the first binding is
    a list or bracket tuple — the flat form always starts with a name
    symbol; flat pairs (let-dim d 128 heads 8) otherwise.
    """
    if isinstance(bindings[0], (list, tuple)):
        pairs = []
        for binding in bindings:
            match binding:
                case [name, value]:
                    pairs.append((name, value))
                case _:
                    raise CompileError(
                        f"let-dim binding must be (<name> <dim>), got {binding!r}"
                    )
        return pairs
    if len(bindings) % 2:
        raise CompileError(f"let-dim expects name/dim pairs, got {form!r}")
    return list(zip(bindings[::2], bindings[1::2]))


def _resolve_dim(form, dim_env):
    """Evaluate a dim expression to a positive int."""
    try:
        value = evaluate(form, dim_env)
    except EvalError as exc:
        raise CompileError(f"bad dim {form!r}: {exc}") from None
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    if not isinstance(value, int) or value <= 0:
        raise CompileError(f"dim must be a positive int, got {value!r} from {form!r}")
    return value


def _compile_block(name, block, dim_env, registry):
    """Compile one block; return (defs, in_dim, out_dim, helpers, entry).

    entry is the function name call sites should use: name for structural
    blocks, the referenced define's own name for block references.
    """
    match block:
        case str() as ref if ref in registry:
            in_dim, out_dim, mangled = registry[ref]
            return [], in_dim, out_dim, set(), mangled
        case str() as ref:
            raise CompileError(f"undefined block '{ref}'")
        case ["mlp", *args]:
            return (*_compile_mlp(name, *_mlp_spec(args, dim_env)), name)
        case ["layernorm", dim]:
            return (*_compile_layernorm(name, _resolve_dim(dim, dim_env)), name)
        case ["embedding", vocab_form, dim_form]:
            vocab = _resolve_dim(vocab_form, dim_env)
            dim = _resolve_dim(dim_form, dim_env)
            return (*_compile_embedding(name, vocab, dim), name)
        case ["attention", *args]:
            positionals, options = _parse_options(args, {"#:causal": "flag"}, "attention")
            match positionals:
                case [dim_form, heads_form]:
                    pass
                case _:
                    raise CompileError(
                        f"attention expects (attention <dim> <heads> #:causal?), "
                        f"got {args!r}"
                    )
            dim = _resolve_dim(dim_form, dim_env)
            heads = _resolve_dim(heads_form, dim_env)
            if dim % heads:
                raise CompileError(
                    f"attention dim {dim} is not divisible by heads {heads}"
                )
            causal = options.get("#:causal", False)
            return (*_compile_attention(name, dim, heads, causal), name)
        case ["chain", *blocks] if blocks:
            return _compile_chain(name, blocks, dim_env, registry)
        case ["residual", *blocks] if blocks:
            return _compile_residual(name, _implicit_chain(blocks), dim_env, registry)
        case ["repeat", count_form, *blocks] if blocks:
            count = _resolve_dim(count_form, dim_env)
            return _compile_repeat(
                name, count, _implicit_chain(blocks), dim_env, registry
            )
        case _:
            raise CompileError(f"unknown block: {block!r}")


def _implicit_chain(blocks):
    """Multi-block bodies (residual, repeat) chain implicitly."""
    return blocks[0] if len(blocks) == 1 else ["chain", *blocks]


def _mlp_spec(args, dim_env):
    positionals, options = _parse_options(args, {"#:activation": "value"}, "mlp")
    match positionals:
        case [in_dim, tuple() as hidden, out_dim]:
            pass
        case [_, list() as hidden, *_]:
            raise CompileError(
                f"mlp hidden dims must be a bracket tuple like [256 256], "
                f"got ({' '.join(map(str, hidden))})"
            )
        case [_, tuple(), _, str() as extra] if extra in ACTIVATIONS:
            raise CompileError(
                f"activation is a keyword option now: use #:activation {extra}"
            )
        case _:
            raise CompileError(
                f"mlp expects (mlp <in> [<hidden>...] <out> #:activation <name>?), "
                f"got {args!r}"
            )
    activation = options.get("#:activation", "gelu")
    if activation not in ACTIVATIONS:
        raise CompileError(
            f"unknown activation {activation!r}, "
            f"expected one of: {' '.join(sorted(ACTIVATIONS))}"
        )
    dims = [_resolve_dim(d, dim_env) for d in (in_dim, *hidden, out_dim)]
    return dims, activation


def _compile_mlp(name, dims, activation):
    n_layers = len(dims) - 1
    inits = ",\n        ".join(
        f"_init_dense(keys[{i}], {dims[i]}, {dims[i + 1]})" for i in range(n_layers)
    )
    defs = f'''
def {_init_of(name)}(key):
    keys = jax.random.split(key, {n_layers})
    return [
        {inits},
    ]


def {name}(params, x):
    for W in params[:-1]:
        x = {ACTIVATIONS[activation]}(x @ W)
    return x @ params[-1]
'''
    return [defs], dims[0], dims[-1], {"dense"}


def _compile_layernorm(name, dim):
    defs = f'''
def {_init_of(name)}(key):
    return jnp.ones({dim}), jnp.zeros({dim})


def {name}(params, x):
    scale, shift = params
    mean = x.mean(axis=-1, keepdims=True)
    var = x.var(axis=-1, keepdims=True)
    return scale * (x - mean) / jnp.sqrt(var + 1e-5) + shift
'''
    return [defs], dim, dim, set()


def _compile_embedding(name, vocab, dim):
    defs = f'''
def {_init_of(name)}(key):
    return jax.random.normal(key, ({vocab}, {dim})) * 0.02


def {name}(params, x):
    return params[x]
'''
    return [defs], "tokens", dim, set()


def _compile_attention(name, dim, heads, causal):
    head_dim = dim // heads
    mask = ""
    if causal:
        mask = '''    seq = x.shape[-2]
    mask = jnp.tril(jnp.ones((seq, seq), dtype=bool))
    scores = jnp.where(mask, scores, -jnp.inf)
'''
    defs = f'''
def {_init_of(name)}(key):
    keys = jax.random.split(key, 4)
    return [jax.random.normal(k, ({dim}, {dim})) * jnp.sqrt(1.0 / {dim}) for k in keys]


def {name}(params, x):
    Wq, Wk, Wv, Wo = params
    q = _split_heads(x @ Wq, {heads})
    k = _split_heads(x @ Wk, {heads})
    v = _split_heads(x @ Wv, {heads})
    scores = q @ k.swapaxes(-1, -2) / jnp.sqrt({head_dim})
{mask}    out = jax.nn.softmax(scores, axis=-1) @ v
    return _merge_heads(out) @ Wo
'''
    return [defs], dim, dim, {"attention"}


def _compile_residual(name, block, dim_env, registry):
    defs, sub_in, sub_out, helpers, entry = _compile_block(
        _sub_name(name, "inner"), block, dim_env, registry
    )
    if sub_in != sub_out:
        raise CompileError(
            f"residual requires matching in/out dims in {name}, "
            f"got {sub_in} -> {sub_out}"
        )
    defs = defs + [f'''
def {_init_of(name)}(key):
    return {_init_of(entry)}(key)


def {name}(params, x):
    return x + {entry}(params, x)
''']
    return defs, sub_in, sub_out, helpers, name


def _compile_repeat(name, count, block, dim_env, registry):
    defs, sub_in, sub_out, helpers, entry = _compile_block(
        _sub_name(name, "body"), block, dim_env, registry
    )
    if sub_in != sub_out:
        raise CompileError(
            f"repeat requires matching in/out dims in {name}, "
            f"got {sub_in} -> {sub_out}"
        )
    defs = defs + [f'''
def {_init_of(name)}(key):
    return [{_init_of(entry)}(k) for k in jax.random.split(key, {count})]


def {name}(params, x):
    for layer_params in params:
        x = {entry}(layer_params, x)
    return x
''']
    return defs, sub_in, sub_out, helpers, name


def _compile_chain(name, blocks, dim_env, registry):
    defs = []
    helpers = set()
    dims = []
    entries = []
    for i, sub_block in enumerate(blocks):
        sub_defs, sub_in, sub_out, sub_helpers, entry = _compile_block(
            _sub_name(name, f"layer{i}"), sub_block, dim_env, registry
        )
        defs.extend(sub_defs)
        helpers |= sub_helpers
        dims.append((sub_in, sub_out))
        entries.append(entry)
    for i in range(len(dims) - 1):
        if dims[i][1] != dims[i + 1][0]:
            raise CompileError(
                f"chain dimension mismatch in {name}: layer {i} outputs "
                f"{dims[i][1]} but layer {i + 1} expects {dims[i + 1][0]}"
            )
    inits = ", ".join(f"{_init_of(e)}(keys[{i}])" for i, e in enumerate(entries))
    applies = "\n".join(
        f"    x = {e}(params[{i}], x)" for i, e in enumerate(entries)
    )
    defs.append(f'''
def {_init_of(name)}(key):
    keys = jax.random.split(key, {len(blocks)})
    return [{inits}]


def {name}(params, x):
{applies}
    return x
''')
    return defs, dims[0][0], dims[-1][1], helpers, name


def main():
    if len(sys.argv) not in (2, 3):
        print("usage: python compiler.py model.jisp [out.py]", file=sys.stderr)
        sys.exit(2)
    in_path = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) == 3 else str(Path(in_path).with_suffix(".py"))
    with open(in_path) as f:
        source = f.read()
    try:
        output = compile_source(source)
    except (ParseError, CompileError) as exc:
        print(f"compile error: {exc}", file=sys.stderr)
        sys.exit(1)
    with open(out_path, "w") as f:
        f.write(output)
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
